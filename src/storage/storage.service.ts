import { Injectable, NotFoundException } from '@nestjs/common';
import { createReadStream } from 'node:fs';
import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve, sep } from 'node:path';
import { Readable } from 'node:stream';
import { optionalEnv } from '../common/config.js';

/**
 * Private file storage for vendor KYC documents. Files live on local disk under
 * UPLOAD_DIR (default ./uploads) and are only ever served through authenticated
 * endpoints. Swap this class for a DigitalOcean Spaces one without touching callers.
 */
@Injectable()
export class StorageService {
  private readonly root = resolve(optionalEnv('UPLOAD_DIR', 'uploads'));

  async save(key: string, data: Buffer): Promise<void> {
    const path = this.pathFor(key);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, data);
  }

  async read(key: string): Promise<Readable> {
    const path = this.pathFor(key);
    await stat(path).catch(() => {
      throw new NotFoundException('File not found.');
    });
    return createReadStream(path);
  }

  /** The whole file in memory, or null when there is none. For small files only. */
  async readBuffer(key: string): Promise<Buffer | null> {
    return readFile(this.pathFor(key)).catch(() => null);
  }

  async remove(key: string): Promise<void> {
    await rm(this.pathFor(key), { force: true });
  }

  /** Keys are generated by us, but never let one escape the storage root. */
  private pathFor(key: string): string {
    const path = resolve(this.root, key);
    if (!path.startsWith(this.root + sep)) {
      throw new NotFoundException('File not found.');
    }
    return path;
  }
}
